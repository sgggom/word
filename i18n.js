function cnum(n){
  const d='零一二三四五六七八九';
  if(n<10) return d[n];
  if(n<20) return '十'+(n%10?d[n%10]:'');
  if(n<100) return d[Math.floor(n/10)]+'十'+(n%10?d[n%10]:'');
  const h=Math.floor(n/100), r=n%100;
  return d[h]+'百'+(r===0?'':(r<10?'零'+d[r]:(r<20?'一'+cnum(r):cnum(r))));
}
